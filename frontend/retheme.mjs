// NexusHR theme switcher.
// Usage (from the frontend folder):
//   node retheme.mjs teal | forest | plum | burgundy
//   node retheme.mjs reset
// It re-colours every CSS file in src/ and writes src/theme.css (dark sidebar).
// Originals are kept in .theme-backup/ so you can switch themes or reset at any time.

import fs from 'node:fs'
import path from 'node:path'

const PRESETS = {
  teal:     { hue: 178, sat: 0.62, sidebar: [178, 42, 13] },
  forest:   { hue: 152, sat: 0.55, sidebar: [152, 36, 13] },
  plum:     { hue: 308, sat: 0.50, sidebar: [308, 28, 15] },
  burgundy: { hue: 346, sat: 0.60, sidebar: [346, 36, 15] },
}

const SRC = path.resolve('src')
const BACKUP = path.resolve('.theme-backup')
const GENERATED = path.join(SRC, 'theme.css')

function listCss(dir) {
  const out = []
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) out.push(...listCss(full))
    else if (entry.name.endsWith('.css') && full !== GENERATED) out.push(full)
  }
  return out
}

// ---- colour maths -------------------------------------------------------
function rgbToHsl(r, g, b) {
  r /= 255; g /= 255; b /= 255
  const max = Math.max(r, g, b), min = Math.min(r, g, b)
  const l = (max + min) / 2
  const d = max - min
  if (d === 0) return [0, 0, l]
  const s = d / (1 - Math.abs(2 * l - 1))
  let h
  if (max === r) h = ((g - b) / d) % 6
  else if (max === g) h = (b - r) / d + 2
  else h = (r - g) / d + 4
  h = (h * 60 + 360) % 360
  return [h, s, l]
}

function hslToRgb(h, s, l) {
  const c = (1 - Math.abs(2 * l - 1)) * s
  const x = c * (1 - Math.abs(((h / 60) % 2) - 1))
  const m = l - c / 2
  let r = 0, g = 0, b = 0
  if (h < 60) [r, g, b] = [c, x, 0]
  else if (h < 120) [r, g, b] = [x, c, 0]
  else if (h < 180) [r, g, b] = [0, c, x]
  else if (h < 240) [r, g, b] = [0, x, c]
  else if (h < 300) [r, g, b] = [x, 0, c]
  else [r, g, b] = [c, 0, x]
  return [(r + m) * 255, (g + m) * 255, (b + m) * 255]
}

function luminance([r, g, b]) {
  const f = (v) => {
    v /= 255
    return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4)
  }
  return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)
}

function shiftColor([r, g, b], preset) {
  const [h, s, l] = rgbToHsl(r, g, b)
  // Only recolour the blue/violet family and leave reds, oranges and greens alone.
  if (s < 0.05 || h < 190 || h > 290) return [r, g, b]

  const newHue = (preset.hue + (h - 245) * 0.5 + 360) % 360
  const newSat = Math.min(1, s * preset.sat)

  // Keep the same perceived brightness so text contrast stays the same.
  const target = luminance([r, g, b])
  let lo = 0, hi = 1
  for (let i = 0; i < 24; i++) {
    const mid = (lo + hi) / 2
    if (luminance(hslToRgb(newHue, newSat, mid)) < target) lo = mid
    else hi = mid
  }
  return hslToRgb(newHue, newSat, (lo + hi) / 2)
}

const toHex = (v) => Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, '0')

function recolor(css, preset) {
  const hexRe = /#([0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{4}|[0-9a-fA-F]{3})(?![\w-])/g
  css = css.replace(hexRe, (match, hex) => {
    let r, g, b, a = ''
    if (hex.length <= 4) {
      r = parseInt(hex[0] + hex[0], 16)
      g = parseInt(hex[1] + hex[1], 16)
      b = parseInt(hex[2] + hex[2], 16)
      if (hex.length === 4) a = hex[3] + hex[3]
    } else {
      r = parseInt(hex.slice(0, 2), 16)
      g = parseInt(hex.slice(2, 4), 16)
      b = parseInt(hex.slice(4, 6), 16)
      if (hex.length === 8) a = hex.slice(6, 8)
    }
    const [nr, ng, nb] = shiftColor([r, g, b], preset)
    return '#' + toHex(nr) + toHex(ng) + toHex(nb) + a
  })

  const rgbaRe = /rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)/g
  css = css.replace(rgbaRe, (match, r, g, b, a) => {
    const [nr, ng, nb] = shiftColor([+r, +g, +b], preset)
    const rgb = `${Math.round(nr)}, ${Math.round(ng)}, ${Math.round(nb)}`
    return a === undefined ? `rgb(${rgb})` : `rgba(${rgb}, ${a})`
  })
  return css
}

function sidebarCss(name, [h, s, l]) {
  const c = (sat, light) => `hsl(${h}, ${sat}%, ${light}%)`
  return `/* Generated by retheme.mjs (${name}). Safe to delete; run the script again to recreate. */
.sidebar { background: ${c(s, l)}; border-right: 0; }
.brand { color: #ffffff; }
.brand-light { color: ${c(45, 74)}; }
.nav-label { color: ${c(18, 58)}; }
.nav-item { color: ${c(16, 80)}; }
.nav-item:hover { background: ${c(s - 4, l + 7)}; color: #ffffff; }
.nav-item.active { background: ${c(s - 2, l + 12)}; color: #ffffff; }
.help-card { background: ${c(s - 4, l + 6)}; border-color: ${c(s - 8, l + 13)}; }
.help-card strong { color: #ffffff; }
.help-card p { color: ${c(14, 72)}; }
.help-icon { color: ${c(50, 72)}; }
.coming-soon { background: ${c(s - 2, l + 16)}; color: ${c(40, 86)}; }
.profile { border-top-color: ${c(s - 8, l + 12)}; }
.profile-info strong { color: #ffffff; }
.profile-info span, .profile-menu { color: ${c(12, 64)}; }
.profile-avatar { background: ${c(s - 2, l + 16)}; color: #ffffff; }
`
}

function ensureThemeImport() {
  const appPath = path.join(SRC, 'App.tsx')
  if (!fs.existsSync(appPath)) return
  const text = fs.readFileSync(appPath, 'utf8')
  if (text.includes("import './theme.css'")) return
  const anchor = "import './lifecycle.css'"
  if (!text.includes(anchor)) {
    console.log("Add this line to src/App.tsx after the other imports:  import './theme.css'")
    return
  }
  fs.writeFileSync(appPath, text.replace(anchor, anchor + "\nimport './theme.css'"))
  console.log("Added import './theme.css' to src/App.tsx")
}

function ensureGitignore() {
  const file = path.resolve('.gitignore')
  const line = '.theme-backup/'
  const text = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : ''
  if (!text.includes(line)) fs.writeFileSync(file, text.replace(/\s*$/, '\n') + line + '\n')
}

// ---- main ---------------------------------------------------------------
const choice = (process.argv[2] || '').toLowerCase()
if (!fs.existsSync(SRC)) {
  console.error('Run this from the frontend folder (the one that contains src/).')
  process.exit(1)
}
if (choice !== 'reset' && !PRESETS[choice]) {
  console.log('Usage: node retheme.mjs ' + Object.keys(PRESETS).join(' | ') + ' | reset')
  process.exit(1)
}

const files = listCss(SRC)

// Save originals the first time only, so every run starts from the same colours.
if (!fs.existsSync(BACKUP)) {
  for (const file of files) {
    const dest = path.join(BACKUP, path.relative(SRC, file))
    fs.mkdirSync(path.dirname(dest), { recursive: true })
    fs.copyFileSync(file, dest)
  }
  ensureGitignore()
}

for (const file of files) {
  const original = path.join(BACKUP, path.relative(SRC, file))
  if (!fs.existsSync(original)) continue // a CSS file added after the backup
  const css = fs.readFileSync(original, 'utf8')
  fs.writeFileSync(file, choice === 'reset' ? css : recolor(css, PRESETS[choice]))
}

if (choice === 'reset') {
  fs.writeFileSync(GENERATED, '/* default theme */\n')
  console.log('Theme reset to the original colours.')
} else {
  fs.writeFileSync(GENERATED, sidebarCss(choice, PRESETS[choice].sidebar))
  console.log(`Applied the "${choice}" theme to ${files.length} CSS files.`)
}
ensureThemeImport()
